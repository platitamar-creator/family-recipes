export function quoteOfTheDay(date = new Date()) {
  const start = new Date(date.getFullYear(), 0, 0);
  const day = Math.floor((date - start) / 86400000);
  const idx = (day + date.getFullYear() * 7) % QUOTES.length;
  const [emoji, text] = QUOTES[idx];
  return { emoji, text };
}
